  trellis_exl3_marlin::g_force_tk = (int)tk;
  trellis_exl3_marlin::g_force_tn = (int)tn;
}

std::vector<int64_t> device_info(int64_t device) {
  auto& st = trellis_exl3_marlin::dev_state((int)device);
  int occ = -1;
  auto kernel = trellis_exl3_marlin::select_kernel(256, 128, 128, 0, 2, 4);
  if (kernel) cudaOccupancyMaxActiveBlocksPerMultiprocessor(&occ, kernel, 256, 0);
  return {st.sms, st.max_shared_mem, occ};
}

