struct ThreadCfg {
  int thread_k, thread_n, num_threads;
};

// Same tables and priority as Marlin.
static const ThreadCfg small_cfgs[] = {{128, 128, 256}, {64, 128, 128}, {128, 64, 128}};
static const ThreadCfg large_cfgs[] = {{64, 256, 256}, {64, 128, 128}, {128, 64, 128}};
// AMPERE: the 9..16-row verify path (thread_m_blocks == 1, m8 == false) runs the non-transposed mb=1 kernels, which
// cost 134-162 registers at 256 threads -> only 1 co-resident block per SM. The 128-thread configs fit 2 blocks/SM
// and measure 15-24 % faster at 16 rows on sm_86 (bench/cfg_explore.py), with no change to the <=8-row (m8) path.
static const ThreadCfg wide_cfgs[] = {{64, 128, 128}, {128, 64, 128}, {128, 128, 256}};

// kb = EXL3 bits per weight; K = 6 is staged like Marlin's 8-bit weights (two 16-byte vectors per lane);
// K = 3 byte-exact (3 bits per weight staged: 24 words per 16x16 tile, notes/k3-dense-plan.md section 4).
static int kernel_cache_size(const ThreadCfg& c, int thread_m_blocks, int kb) {
  int tb_k = c.thread_k, tb_n = c.thread_n, tb_m = thread_m_blocks * 16;
  int sh_a_size = kStages * (tb_m * tb_k) * 2;
  int sh_b_size = kb == 5 ? kStages * (tb_k * tb_n * 5 / 8)                        // K5
                : kb == 3 ? kStages * (tb_k * tb_n * 3 / 8)                        // K3
                          : kStages * (tb_k * tb_n / (kb == 4 ? 8 : 4)) * 4;
  int sh_red_size = tb_m * (tb_n + 8) * 2;
  int sh_bias_size = tb_n * 2;
  int tmp_size = (sh_b_size > sh_red_size ? sh_red_size : sh_b_size) + sh_bias_size;
  tmp_size = std::max(std::max(sh_b_size, sh_red_size), tmp_size);
  int sh_s_size = tb_n * 2 * kStages;
  return tmp_size + sh_a_size + sh_s_size;
}

static bool valid_cfg(const ThreadCfg& c, int thread_m_blocks, int n, int k, int kb, int max_shared_mem,
                      const std::vector<int64_t>& shard_ends = {}) {
  if (k % c.thread_k != 0 || n % c.thread_n != 0) return false;
  for (int64_t e : shard_ends)  // a column slice (thread_n wide) must not straddle two shards
    if (e % c.thread_n != 0) return false;
  return kernel_cache_size(c, thread_m_blocks, kb) <= max_shared_mem;
}

static constexpr int kMaxBlocksPerSm = 4;
static int g_blocks_per_sm = 1;  // tuning knob (set_blocks_per_sm); Marlin uses 1
static bool g_out_had_inlaunch = true;  // knob (set_out_had_inlaunch): output transform inside the GEMM launch
static int g_debug_flags = 0;           // timing probes only (set_debug_flags): 4 = kernels return immediately
static bool g_in_had_inlaunch = false;  // knob (set_in_had_inlaunch): input transform as a prologue of a COOPERATIVE
                                        // GEMM launch (grid barrier); experimental
static int g_force_tk = 0, g_force_tn = 0;  // knob (set_force_cfg): per-shape thread config override for the auto path

struct DevState {
  int sms = 0;
  int max_shared_mem = 0;
  at::Tensor locks;  // int32 [sms], zero
  at::Tensor c_tmp;  // float [sms * 64 * 256]
};

static DevState& dev_state(int device) {
  static std::map<int, DevState> states;
  auto it = states.find(device);
  if (it != states.end()) return it->second;
  DevState st;
  cudaDeviceGetAttribute(&st.sms, cudaDevAttrMultiProcessorCount, device);
  cudaDeviceGetAttribute(&st.max_shared_mem, cudaDevAttrMaxSharedMemoryPerBlockOptin, device);
  TORCH_CHECK(st.sms > 0 && st.max_shared_mem > 0, "trellis_exl3: device query failed");
  auto dev = at::Device(at::kCUDA, device);
  st.locks = at::zeros({st.sms * kMaxBlocksPerSm}, at::TensorOptions().dtype(at::kInt).device(dev));
  st.c_tmp = at::empty({(int64_t)st.sms * kMaxBlocksPerSm * 64 * 256}, at::TensorOptions().dtype(at::kFloat).device(dev));
  states[device] = st;
  return states[device];
}

// GEMM on a pre-rotated input. a: fp16 [m, k] contiguous; b: repacked trellis; c: fp16 [m, n].
//
// Multi-matrix: `shard_ends` (ascending column ends of all shards but the last, at most 3) splits n; shard s reads
// the input slab a_ptr + s * prob_m * prob_k. Every shard width must be a multiple of the chosen thread_n.
//
// svh != nullptr: also apply the output transform c = Had128(c) * svh (c as bf16 bits if out_bf16). It runs inside the
// GEMM launch (the block that writes a column slice transforms it in shared memory first) whenever thread_n is a
// multiple of 128, else as a separate launch. Both give the same bits.
static void gemm_launch(const half* a_ptr, const void* b_ptr, half* c_ptr, int prob_m, int prob_n, int prob_k,
                        int cb, int kb, int device, cudaStream_t stream, int force_thread_k, int force_thread_n,
                        const std::vector<int64_t>& shard_ends = {}, const half* svh = nullptr,
                        bool out_bf16 = false, const void* x_raw = nullptr, bool x_bf16 = false,
                        const half* suh = nullptr) {
  // x_raw != nullptr: a_ptr is scratch and must first receive Had128(fp16(x_raw) * suh[s]) per shard: inside the
  // launch (cooperative launch, grid barrier) if enabled and the rows fit one launch, else as its own launch.
  const int in_shards = (int)shard_ends.size() + 1;
  bool in_inlaunch = x_raw && g_in_had_inlaunch && prob_m <= 64;
  if (x_raw && !in_inlaunch) had_in_launch(x_raw, x_bf16, (half*)a_ptr, suh, in_shards, prob_m, prob_k, stream);
  TORCH_CHECK(shard_ends.size() <= 3, "trellis_exl3: at most 4 shards");
  int se[3] = {INT_MAX, INT_MAX, INT_MAX};
  for (size_t i = 0; i < shard_ends.size(); i++) se[i] = (int)shard_ends[i];
  const int a_shard_stride = shard_ends.empty() ? 0 : prob_m * (prob_k / 8);
  DevState& st = dev_state(device);
  const int4* A_ptr = (const int4*)a_ptr;
  const int4* B_ptr = (const int4*)b_ptr;
  int4* C_ptr = (int4*)c_ptr;
  int4* C_tmp_ptr = (int4*)st.c_tmp.data_ptr();
  int* locks = (int*)st.locks.data_ptr();
  int lda = prob_k;
  int sms = st.sms;
  int max_shared_mem = st.max_shared_mem;

  int max_par = 16;
  if (prob_n <= 4096) max_par = 16 * 8;
  int rest_m = prob_m;
  int max_thread_m_blocks = 4;
  while (rest_m) {
    int par_count = rest_m / (max_thread_m_blocks * 16);
    if (par_count > max_par) par_count = max_par;
    int prob_m_split = par_count > 0 ? (par_count * (max_thread_m_blocks * 16)) : rest_m;
    int thread_m_blocks = std::min((prob_m_split + 15) / 16, max_thread_m_blocks);
    bool m8 = prob_m_split <= 8;
    // EXL3: global per-shape thread-config override (set_force_cfg), honoured only when valid for this shape.
    if (force_thread_k <= 0 && g_force_tk > 0) {
      ThreadCfg gc{g_force_tk, g_force_tn,
                   (g_force_tk == 64 && g_force_tn == 128) || (g_force_tk == 128 && g_force_tn == 64) ? 128 : 256};
      if (valid_cfg(gc, thread_m_blocks, prob_n, prob_k, kb, max_shared_mem - 512, shard_ends)) {
        force_thread_k = g_force_tk; force_thread_n = g_force_tn;
      }
    }

    ThreadCfg cfg{-1, -1, -1};
    if (force_thread_k > 0 && force_thread_n > 0) {
      cfg = ThreadCfg{force_thread_k, force_thread_n,
                      (force_thread_k == 64 && force_thread_n == 128) || (force_thread_k == 128 && force_thread_n == 64)
                          ? 128 : 256};
      TORCH_CHECK(valid_cfg(cfg, thread_m_blocks, prob_n, prob_k, kb, max_shared_mem - 512), "trellis_exl3: bad forced config");
    } else {
      const ThreadCfg* cfgs = thread_m_blocks > 1 ? large_cfgs : (m8 ? small_cfgs : wide_cfgs);
      for (int i = 0; i < 3; i++) {
        if (!valid_cfg(cfgs[i], thread_m_blocks, prob_n, prob_k, kb, max_shared_mem - 512, shard_ends)) continue;
        cfg = cfgs[i];
        break;
      }
      if (cfg.thread_n != -1) {
        if (prob_n / cfg.thread_n * ((prob_m_split + thread_m_blocks * 16 - 1) / (thread_m_blocks * 16)) * 4 <= sms) {
          ThreadCfg narrow{128, 64, 128};
          if (valid_cfg(narrow, thread_m_blocks, prob_n, prob_k, kb, max_shared_mem, shard_ends)) cfg = narrow;
        }
      }
      if (cfg.thread_k == -1 && max_thread_m_blocks > 1) {
        max_thread_m_blocks--;
        continue;
      }
    }
    TORCH_CHECK(cfg.thread_k != -1, "trellis_exl3: no thread config for m=", prob_m, " k=", prob_k, " n=", prob_n);

    FuncPtr kernel = select_kernel(cfg.num_threads, cfg.thread_n, cfg.thread_k, m8 ? 0 : thread_m_blocks, cb, kb);
    for (size_t i = 0; i < shard_ends.size(); i++)
      TORCH_CHECK(shard_ends[i] % cfg.thread_n == 0, "trellis_exl3: shard end ", shard_ends[i],
                  " is not a multiple of thread_n = ", cfg.thread_n);
    TORCH_CHECK(kernel != nullptr, "trellis_exl3: kernel not compiled: threads=", cfg.num_threads,
                " thread_n=", cfg.thread_n, " thread_k=", cfg.thread_k, " m_blocks=", thread_m_blocks, " cb=", cb, " K=", kb);

    // AMPERE: blocks per SM is a per-launch fit, not a hard requirement. With g_blocks_per_sm > 1 the request is honoured
    // only when this config's shared memory fits that many co-resident blocks (100 KB per SM on sm_86: the rows<=16
    // families fit 2, the 64-row family and K=6 do not); otherwise the launch silently uses 1 block per SM.
    const int need = kernel_cache_size(cfg, thread_m_blocks, kb);
    int bps = g_blocks_per_sm;
    while (bps > 1 && need > max_shared_mem / bps - 1024) bps--;
    int smem = bps > 1 ? max_shared_mem / bps - 1024 : max_shared_mem;
    if (in_inlaunch && bps > 1) {
      // a cooperative launch needs every block co-resident: registers, not only shared memory, bound that
      int occ = 1;
      cudaFuncSetAttribute(kernel, cudaFuncAttributeMaxDynamicSharedMemorySize, smem);
      cudaOccupancyMaxActiveBlocksPerMultiprocessor(&occ, kernel, cfg.num_threads, smem);
      if (occ < bps) { bps = occ > 0 ? occ : 1; smem = bps > 1 ? max_shared_mem / bps - 1024 : max_shared_mem; }
    }
    TORCH_CHECK(need <= smem, "trellis_exl3: shared memory too small (", need, " > ", smem, ")");
    cudaFuncSetAttribute(kernel, cudaFuncAttributeMaxDynamicSharedMemorySize, smem);
    // clang-format off
    const int out_flags = (svh && g_out_had_inlaunch && cfg.thread_n % 128 == 0) ? (1 | (out_bf16 ? 2 : 0)) : 0;
    if (in_inlaunch) {
      // cooperative launch: arguments by address, in kernel parameter order (TRELLIS_KERNEL_PARAMS)
      const int4* a_bias = (const int4*)svh; const float* a_fnull = nullptr; const int4* a_inull = nullptr;
      const int* a_gidx = nullptr; int a_zero = 0; bool a_false = false, a_true = true;
      const int4* a_x = (const int4*)x_raw; const int4* a_suh = (const int4*)suh;
      int a_inflags = 1 | (x_bf16 ? 2 : 0), a_shards = in_shards, a_outflags = out_flags, a_smem = smem;
      void* args[] = {&A_ptr, &B_ptr, &C_ptr, &C_tmp_ptr, &a_bias, &a_fnull, &a_inull, &a_fnull, &a_inull, &a_gidx,
                      &a_zero, &prob_m_split, &prob_n, &prob_k, &lda, &locks, &a_false, &a_false, &a_true, &a_smem,
                      (void*)&a_shard_stride, &se[0], &se[1], &se[2], &a_outflags, &a_x, &a_suh, &a_inflags,
                      &a_shards};
      cudaLaunchCooperativeKernel((void*)kernel, sms * bps, cfg.num_threads, args, smem, stream);
    } else {
      kernel<<<sms * bps, cfg.num_threads, smem, stream>>>(
          A_ptr, B_ptr, C_ptr, C_tmp_ptr, (const int4*)svh, nullptr, nullptr, nullptr, nullptr, nullptr, 0,
          prob_m_split, prob_n, prob_k, lda, locks, false, false, true, smem,
          a_shard_stride, se[0], se[1], se[2], out_flags, nullptr, nullptr, g_debug_flags, 1);
    }
    // clang-format on
    if (svh && !out_flags) ::had_out_launch((void*)C_ptr, out_bf16, svh, prob_m_split, prob_n, stream);

    A_ptr += prob_m_split * (lda / 8);
    C_ptr += prob_m_split * (prob_n / 8);
    rest_m -= prob_m_split;
  }
}

