// Hadamard launches (ExLlamaV3's arithmetic, exl3_had.cuh; bf16 <-> fp16 conversion at the boundary when asked)

// Block (x, y) transforms the 128-block y of output row x. Input row = x % rows, scale vector = x / rows:
//  - input transform of a fused group: grid (shards * rows, k / 128), slab s (rows x k) = Had128(x * suh[s]);
//  - single matrix / output transform: grid (rows, cols / 128), `rows` = all rows.
// in_stride / out_stride: elements per row of the input / output buffer (>= the transformed width gridDim.y * 128;
// larger when the output is a column span of a wider fused tensor).
static constexpr float kHadScale = 0.088388347648f;  // 1/sqrt(128)

// WARPS: 128-blocks per thread block (1 warp each; the transform only shuffles inside a warp). 8 = one 256-thread block
// per 8 consecutive 128-blocks of a row (many-row path: 8x fewer thread blocks to schedule), 1 = a 32-thread block per
// 128-block (decode: the launch is pure launch cost either way).
template <bool in_bf16, bool out_bf16, bool pre_scale, bool post_scale, int WARPS>
__global__ __launch_bounds__(32 * WARPS)
void trellis_had_r_128_kernel(const half* __restrict__ input_ptr, half* __restrict__ output_ptr,
                             const half* __restrict__ scales, const int rows, const float r_scale,
                             const size_t in_stride, const size_t out_stride) {
  const size_t width = (size_t)gridDim.y * 128 * WARPS;
  const size_t blk = (size_t)blockIdx.y * WARPS + threadIdx.x / 32;
  input_ptr += in_stride * (blockIdx.x % rows) + blk * 128;
  output_ptr += out_stride * blockIdx.x + blk * 128;
  trellis_had_r_128_inner<in_bf16, out_bf16, pre_scale, post_scale>(
      input_ptr, output_ptr, scales + width * (blockIdx.x / rows), (int)blk * 32, r_scale);
}

static int g_had_warps = 8;  // knob (set_had_warps): 128-blocks per thread block on the many-row path (1 or 8)
static constexpr int kHadWarpsMinRows = 32;

#define TRELLIS_HAD_LAUNCH(IN, OUT, PRE, POST, in, out, sc, rows_, nblk, grid_x, in_stride, out_stride)                   \
  if (g_had_warps == 8 && (nblk) % 8 == 0 && (rows_) >= kHadWarpsMinRows)                                                  \
    trellis_had_r_128_kernel<IN, OUT, PRE, POST, 8><<<dim3(grid_x, (nblk) / 8), 256, 0, stream>>>(                         \
        in, out, sc, rows_, kHadScale, in_stride, out_stride);                                                             \
  else                                                                                                                     \
    trellis_had_r_128_kernel<IN, OUT, PRE, POST, 1><<<dim3(grid_x, nblk), 32, 0, stream>>>(                                 \
        in, out, sc, rows_, kHadScale, in_stride, out_stride)


// xh[s] = Had128(fp16(x) * suh[s]) for s < shards. x: fp16 or bf16 bits [rows, k]; xh: fp16 [shards * rows, k].
static void had_in_launch(const void* x, bool x_bf16, half* xh, const half* suh, int shards, int rows, int k,
                          cudaStream_t stream) {
  if (x_bf16) {
    TRELLIS_HAD_LAUNCH(true, false, true, false, (const half*)x, xh, suh, rows, k / 128, shards * rows, (size_t)k, (size_t)k);
  } else {
    TRELLIS_HAD_LAUNCH(false, false, true, false, (const half*)x, xh, suh, rows, k / 128, shards * rows, (size_t)k, (size_t)k);
  }
}

// out = Had128(y) * svh; y: fp16 [rows, n] (row stride n); out: fp16 or bf16 bits, row stride out_stride (out == y
// with out_stride == n is the in-place form; a larger stride writes a column span of a wider fused output).
static void had_out_launch_to(const void* y, void* out, size_t out_stride, bool out_bf16, const half* svh, int rows,
                              int n, cudaStream_t stream) {
  if (out_bf16) {
    TRELLIS_HAD_LAUNCH(false, true, false, true, (const half*)y, (half*)out, svh, rows, n / 128, rows, (size_t)n, out_stride);
  } else {
    TRELLIS_HAD_LAUNCH(false, false, false, true, (const half*)y, (half*)out, svh, rows, n / 128, rows, (size_t)n, out_stride);
  }
}

// y = Had128(y) * svh in place; y holds fp16 bits on entry and fp16 or bf16 bits on exit.
static void had_out_launch(void* y, bool y_bf16, const half* svh, int rows, int n, cudaStream_t stream) {
  had_out_launch_to(y, y, (size_t)n, y_bf16, svh, rows, n, stream);
}

