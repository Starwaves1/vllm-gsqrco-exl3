// -> EXL3 bits per weight of a repacked trellis: [k/16, n/64, 32, 4] = K 4, [k/16, n/64, 32, 4, 2] = K 6,
// [k/16, n/64, 4, 24] = K 3 (K3: the tiles exactly as stored, 24 words each), [k/16, n/64, 4, 40] = K 5 (K5, 40 words)
static int kbits_from_trellis_check(const at::Tensor& b, int64_t k, int64_t n) {
  TORCH_CHECK(b.is_cuda() && b.is_contiguous(), "repacked trellis must be a contiguous CUDA tensor");
  TORCH_CHECK(b.dtype() == at::kInt, "repacked trellis must be int32 (use repack_trellis)");
  const bool k3 = b.dim() == 4 && b.size(2) == 4 && b.size(3) == 24;   // K3
  const bool k5 = b.dim() == 4 && b.size(2) == 4 && b.size(3) == 40;   // K5
  TORCH_CHECK(k3 || k5 || ((b.dim() == 4 || (b.dim() == 5 && b.size(4) == 2)) && b.size(2) == 32 && b.size(3) == 4),
              "repacked trellis must be [k/16, n/64, 32, 4] (K=4), [k/16, n/64, 32, 4, 2] (K=6), [k/16, n/64, 4, 24] (K=3) or [k/16, n/64, 4, 40] (K=5)");
  TORCH_CHECK(b.size(0) * 16 == k && b.size(1) * 64 == n, "repacked trellis shape does not match k, n");
  return k5 ? 5 : k3 ? 3 : (b.dim() == 4 ? 4 : 6);   // K5
}

static bool is_16bit_float(const at::Tensor& t) { return t.dtype() == at::kHalf || t.dtype() == at::kBFloat16; }

// EXL3 trellis int16 [k/16, n/16, 16K] -> lane-major int32.
//
// K = 4 -> [k/16, n/64, 32, 4]: pure permutation of the 32-bit stream words: word l of tile (i, 4g + j) moves to
// [i, g, l, j], so one 16-byte vector holds lane l's stream word for the 4 adjacent n-tiles of a warp (= Marlin's
// 4-bit B indexing).
//
// K = 6 -> [k/16, n/64, 32, 4, 2]: a tile is 48 stream words = 1536 bits, bit 0 = MSB of word 0.
// Lane l decodes positions 8l..8l+7 = windows reaching from bit 48l - 10 to 48l + 48, which straddle 2-3 stream
// words at lane-dependent offsets. Entry [i, g, l, j] = (hi, lo) = the 64 stream bits [48l - 16, 48l + 48) of tile
// (i, 4g + j), tail-biting (= Marlin's 8-bit B indexing: two vectors per lane, ints 2j, 2j+1 belong to n-tile j).
// A lossless bit re-layout: every stream bit is kept, the 16 bits before each lane's own 48 are stored twice
// (8 bits per weight resident instead of 6). `unpack_trellis` inverts it exactly.
//
// K3: K = 3 -> [k/16, n/64, 4, 24]: the tiles exactly as stored (24 little-endian uint32 words = 768 bits each), a pure
// view of the int16 trellis as int32 (3 bits per weight resident; the kernel stages tiles byte-exact and every lane
// gathers its two words, exl3_decode.cuh k3_lane_words / dq8_regs_3bits). Same layout as the MoE front's K = 3 stack.
// K5: K = 5 -> [k/16, n/64, 4, 40]: likewise the tiles as stored (40 words = 1280 bits each; lanes gather four words,
// k5_lane_words / dq8_regs_5bits).
at::Tensor repack_trellis(const at::Tensor& trellis) {
  TORCH_CHECK(trellis.dim() == 3 && trellis.dtype() == at::kShort, "trellis must be int16 [k/16, n/16, 16K]");
  TORCH_CHECK(trellis.size(2) == 48 || trellis.size(2) == 64 || trellis.size(2) == 80 || trellis.size(2) == 96,
              "only K = 3, 4, 5 and 6 are supported");   // K5
  TORCH_CHECK(trellis.size(1) % 8 == 0 && trellis.size(0) % 8 == 0, "k and n must be multiples of 128");
  int64_t kt = trellis.size(0), nt = trellis.size(1);
  if (trellis.size(2) == 80) {   // K5
    return trellis.contiguous().view(at::kInt).view({kt, nt / 4, 4, 40}).contiguous();
  }
  if (trellis.size(2) == 48) {   // K3
    return trellis.contiguous().view(at::kInt).view({kt, nt / 4, 4, 24}).contiguous();
  }
  if (trellis.size(2) == 64) {
    auto w = trellis.contiguous().view(at::kInt);  // [kt, nt, 32], little-endian uint16 pairs (as ExLlamaV3 reads it)
    return w.view({kt, nt / 4, 4, 32}).permute({0, 1, 3, 2}).contiguous();
  }
  auto opts_l = at::TensorOptions().dtype(at::kLong).device(trellis.device());
  std::vector<int64_t> q0(32), q1(32), q2(32), odd(32);
  for (int l = 0; l < 32; l++) {
    int s = (48 * l - 16 + 1536) % 1536;  // first stored bit; s % 32 == 0 for odd lanes, 16 for even lanes
    q0[l] = s / 32; q1[l] = (s / 32 + 1) % 48; q2[l] = (s / 32 + 2) % 48; odd[l] = l & 1;
  }
  auto i0 = at::tensor(q0, opts_l), i1 = at::tensor(q1, opts_l), i2 = at::tensor(q2, opts_l);
  auto is_odd = at::tensor(odd, opts_l).to(at::kBool);
  auto out = at::empty({kt, nt / 4, 32, 4, 2}, at::TensorOptions().dtype(at::kInt).device(trellis.device()));
  const int64_t chunk = 16;
  for (int64_t r0 = 0; r0 < kt; r0 += chunk) {
    int64_t r1 = std::min(kt, r0 + chunk);
    auto w = trellis.slice(0, r0, r1).contiguous().view(at::kInt).to(at::kLong).bitwise_and(0xffffffffLL);  // [c, nt, 48]
    auto x0 = w.index_select(2, i0), x1 = w.index_select(2, i1), x2 = w.index_select(2, i2);               // [c, nt, 32]
    auto hi = at::where(is_odd, x0, x0.bitwise_left_shift(16).bitwise_or(x1.bitwise_right_shift(16)).bitwise_and(0xffffffffLL));
    auto lo = at::where(is_odd, x1, x1.bitwise_left_shift(16).bitwise_or(x2.bitwise_right_shift(16)).bitwise_and(0xffffffffLL));
    auto both = at::stack({hi, lo}, 3);                                   // [c, nt, 32, 2], values 0 .. 2^32-1
    both = at::where(both.ge(0x80000000LL), both - 0x100000000LL, both).to(at::kInt);
    out.slice(0, r0, r1).copy_(both.view({r1 - r0, nt / 4, 4, 32, 2}).permute({0, 1, 3, 2, 4}));
  }
  return out;
}

// Inverse of repack_trellis (parity, on-demand prefill unpack). K = 6: the stream is rebuilt from each lane's own 48 bits.
at::Tensor unpack_trellis(const at::Tensor& b) {
  TORCH_CHECK((b.dim() == 4 || b.dim() == 5) && b.dtype() == at::kInt);
  int64_t kt = b.size(0), g = b.size(1);
  if (b.dim() == 4 && b.size(2) == 4 && b.size(3) == 40)   // K5: same bytes, same order
    return b.contiguous().view({kt, g * 4, 40}).view(at::kShort);
  if (b.dim() == 4 && b.size(2) == 4 && b.size(3) == 24)   // K3: same bytes, same order
    return b.contiguous().view({kt, g * 4, 24}).view(at::kShort);
  if (b.dim() == 4) return b.permute({0, 1, 3, 2}).contiguous().view({kt, g * 4, 32}).view(at::kShort);
  auto out = at::empty({kt, g * 4, 48}, at::TensorOptions().dtype(at::kInt).device(b.device()));
  const int64_t chunk = 16;
  for (int64_t r0 = 0; r0 < kt; r0 += chunk) {
    int64_t r1 = std::min(kt, r0 + chunk), c = r1 - r0;
    auto t = b.slice(0, r0, r1).permute({0, 1, 3, 2, 4}).reshape({c, g * 4, 32, 2}).to(at::kLong).bitwise_and(0xffffffffLL);
    auto own = t.select(3, 0).bitwise_and(0xffffLL).bitwise_left_shift(32).bitwise_or(t.select(3, 1));  // [c, nt, 32] 48 bits
    auto pair = own.view({c, g * 4, 16, 2});
    auto e = pair.select(3, 0), o = pair.select(3, 1);                       // lanes 2v, 2v+1 own words 3v, 3v+1, 3v+2
    auto w0 = e.bitwise_right_shift(16);
    auto w1 = e.bitwise_and(0xffffLL).bitwise_left_shift(16).bitwise_or(o.bitwise_right_shift(32));
    auto w2 = o.bitwise_and(0xffffffffLL);
    auto w = at::stack({w0, w1, w2}, 3).view({c, g * 4, 48});
    w = at::where(w.ge(0x80000000LL), w - 0x100000000LL, w).to(at::kInt);
    out.slice(0, r0, r1).copy_(w);
  }
  return out.view(at::kShort);
}

// c = a @ W_hat (rotated basis, no Hadamards). a fp16 [m, k], c fp16 [m, n].
void exl3_gemm_marlin(const at::Tensor& a, const at::Tensor& b, at::Tensor& c, int64_t cb, int64_t thread_k,
                      int64_t thread_n) {
  const at::cuda::OptionalCUDAGuard device_guard(a.device());
  TORCH_CHECK(a.dim() == 2 && c.dim() == 2 && a.dtype() == at::kHalf && c.dtype() == at::kHalf);
  TORCH_CHECK(a.is_contiguous() && c.is_contiguous());
  int64_t m = a.size(0), k = a.size(1), n = c.size(1);
  TORCH_CHECK(c.size(0) == m);
  int kb = kbits_from_trellis_check(b, k, n);
  if (m == 0) return;
  cudaStream_t stream = at::cuda::getCurrentCUDAStream().stream();
  trellis_exl3_marlin::gemm_launch((const half*)a.data_ptr(), b.data_ptr(), (half*)c.data_ptr(), (int)m, (int)n, (int)k,
                                  (int)cb, kb, a.get_device(), stream, (int)thread_k, (int)thread_n);
}

// Rotated-basis GEMM of a fused group: a_all fp16 [shards * m, k] (slab s = rows s*m .. s*m+m-1), c [m, n_total].
void exl3_gemm_marlin_multi(const at::Tensor& a_all, const at::Tensor& b, at::Tensor& c,
                            std::vector<int64_t> shard_ends, int64_t cb) {
  const at::cuda::OptionalCUDAGuard device_guard(a_all.device());
  TORCH_CHECK(a_all.dim() == 2 && c.dim() == 2 && a_all.dtype() == at::kHalf && c.dtype() == at::kHalf);
  TORCH_CHECK(a_all.is_contiguous() && c.is_contiguous());
  int64_t shards = (int64_t)shard_ends.size() + 1, m = c.size(0), k = a_all.size(1), n = c.size(1);
  TORCH_CHECK(a_all.size(0) == shards * m);
  int kb = kbits_from_trellis_check(b, k, n);
  cudaStream_t stream = at::cuda::getCurrentCUDAStream().stream();
  trellis_exl3_marlin::gemm_launch((const half*)a_all.data_ptr(), b.data_ptr(), (half*)c.data_ptr(), (int)m, (int)n,
                                  (int)k, (int)cb, kb, a_all.get_device(), stream, -1, -1, shard_ends);
}

// out = Had128(in * scale) (pre = true) or Had128(in) * scale (pre = false); in place allowed.
// in / out may be fp16 or bf16 (pre: bf16 -> fp16 on load; post: fp16 -> bf16 on store; see exl3_had.cuh).
void had_r_128_marlin(const at::Tensor& in, at::Tensor& out, const at::Tensor& scale, bool pre) {
  const at::cuda::OptionalCUDAGuard device_guard(in.device());
  TORCH_CHECK(in.dim() == 2 && is_16bit_float(in) && is_16bit_float(out) && scale.dtype() == at::kHalf);
  TORCH_CHECK(in.size(1) % 128 == 0 && scale.numel() == in.size(1) && in.is_contiguous() && out.is_contiguous());
  cudaStream_t stream = at::cuda::getCurrentCUDAStream().stream();
  if (pre) {
    TORCH_CHECK(out.dtype() == at::kHalf, "input transform writes fp16");
    had_in_launch(in.data_ptr(), in.dtype() == at::kBFloat16, (half*)out.data_ptr(), (const half*)scale.data_ptr(), 1,
                  (int)in.size(0), (int)in.size(1), stream);
  } else {
    // the transform reads fp16 bits and works in place; a bf16 `in` is only legal as the in-place buffer itself
    TORCH_CHECK(in.dtype() == at::kHalf || in.data_ptr() == out.data_ptr(), "output transform reads fp16");
    if (in.data_ptr() != out.data_ptr()) out.view(at::kHalf).copy_(in);
    had_out_launch(out.data_ptr(), out.dtype() == at::kBFloat16, (const half*)scale.data_ptr(), (int)in.size(0),
                   (int)in.size(1), stream);
  }
}

// Many-row (prefill) building blocks: the two transforms around a dense GEMM on the decoded weight.
// xh[s] = Had128(fp16(x) * suh_cat[s]) for every shard s in ONE launch. x fp16 | bf16 [rows, k], xh fp16 [shards * rows, k].
void had_in_group_marlin(const at::Tensor& x, at::Tensor& xh, const at::Tensor& suh_cat) {
  const at::cuda::OptionalCUDAGuard device_guard(x.device());
  TORCH_CHECK(x.dim() == 2 && is_16bit_float(x) && x.is_contiguous() && x.size(1) % 128 == 0);
  int64_t rows = x.size(0), k = x.size(1);
  TORCH_CHECK(suh_cat.dtype() == at::kHalf && suh_cat.is_contiguous() && suh_cat.numel() % k == 0);
  int64_t shards = suh_cat.numel() / k;
  TORCH_CHECK(xh.dtype() == at::kHalf && xh.is_contiguous() && xh.numel() >= shards * rows * k);
  if (rows == 0) return;
  had_in_launch(x.data_ptr(), x.dtype() == at::kBFloat16, (half*)xh.data_ptr(), (const half*)suh_cat.data_ptr(),
                (int)shards, (int)rows, (int)k, at::cuda::getCurrentCUDAStream().stream());
}

// out[:, col0 : col0 + n] = Had128(y) * svh, stored in out's dtype (fp16 | bf16). y fp16 [rows, n] contiguous;
// out [rows, n_total] contiguous: the result goes straight into its column span, no temporary, no cast launch.
void had_out_into_marlin(const at::Tensor& y, const at::Tensor& svh, at::Tensor& out, int64_t col0) {
  const at::cuda::OptionalCUDAGuard device_guard(y.device());
  TORCH_CHECK(y.dim() == 2 && y.dtype() == at::kHalf && y.is_contiguous() && y.size(1) % 128 == 0);
  TORCH_CHECK(out.dim() == 2 && is_16bit_float(out) && out.is_contiguous() && out.size(0) == y.size(0));
  TORCH_CHECK(col0 >= 0 && col0 + y.size(1) <= out.size(1));
  TORCH_CHECK(svh.dtype() == at::kHalf && svh.is_contiguous() && svh.numel() == y.size(1));
  if (y.size(0) == 0) return;
  had_out_launch_to(y.data_ptr(), (char*)out.data_ptr() + 2 * col0, (size_t)out.size(1), out.dtype() == at::kBFloat16,
                    (const half*)svh.data_ptr(), (int)y.size(0), (int)y.size(1), at::cuda::getCurrentCUDAStream().stream());
}

// y = Had(x * suh) @ W_hat -> Had -> * svh.  Writes into `y`, uses caller-owned scratch `xh` (fp16, >= m * k).
// x and y are fp16 or bf16 independently; the GEMM itself always runs on fp16 (ExLlamaV3 semantics). With bf16 the
// result equals `f(x.to(fp16)).to(bf16)` bit for bit: the conversions are torch's value conversions.
void exl3_linear_marlin_out(const at::Tensor& x, const at::Tensor& b, const at::Tensor& suh, const at::Tensor& svh,
                            int64_t cb, at::Tensor& xh, at::Tensor& y) {
  const at::cuda::OptionalCUDAGuard device_guard(x.device());
  TORCH_CHECK(x.dim() == 2 && is_16bit_float(x) && x.is_contiguous());
  int64_t m = x.size(0), k = x.size(1), n = y.size(1);
  int kb = kbits_from_trellis_check(b, k, n);
  TORCH_CHECK(xh.dtype() == at::kHalf && xh.numel() >= m * k && xh.is_contiguous());
  TORCH_CHECK(is_16bit_float(y) && y.dim() == 2 && y.size(0) == m && y.is_contiguous());
  TORCH_CHECK(suh.numel() == k && svh.numel() == n && suh.dtype() == at::kHalf && svh.dtype() == at::kHalf);
  TORCH_CHECK(suh.is_contiguous() && svh.is_contiguous());
  if (m == 0) return;
  cudaStream_t stream = at::cuda::getCurrentCUDAStream().stream();
  trellis_exl3_marlin::gemm_launch((const half*)xh.data_ptr(), b.data_ptr(), (half*)y.data_ptr(), (int)m, (int)n, (int)k,
                                  (int)cb, kb, x.get_device(), stream, -1, -1, {}, (const half*)svh.data_ptr(),
                                  y.dtype() == at::kBFloat16, x.data_ptr(), x.dtype() == at::kBFloat16,
                                  (const half*)suh.data_ptr());
}

// Fused group (same input, same k, same K/codebook): b = repacked trellises concatenated along dim 1,
// suh_cat [shards, k], svh_cat [n_total], shard_ends = column ends of all shards but the last.
// xh: scratch fp16 >= shards * m * k.  y: [m, n_total], fp16 or bf16 (as x).
void exl3_linear_marlin_multi_out(const at::Tensor& x, const at::Tensor& b, const at::Tensor& suh_cat,
                                  const at::Tensor& svh_cat, std::vector<int64_t> shard_ends, int64_t cb,
                                  at::Tensor& xh, at::Tensor& y) {
  const at::cuda::OptionalCUDAGuard device_guard(x.device());
  TORCH_CHECK(x.dim() == 2 && is_16bit_float(x) && x.is_contiguous());
  int64_t m = x.size(0), k = x.size(1), n = y.size(1), shards = (int64_t)shard_ends.size() + 1;
  int kb = kbits_from_trellis_check(b, k, n);
  TORCH_CHECK(xh.dtype() == at::kHalf && xh.numel() >= shards * m * k && xh.is_contiguous());
  TORCH_CHECK(is_16bit_float(y) && y.dim() == 2 && y.size(0) == m && y.is_contiguous());
  TORCH_CHECK(suh_cat.dtype() == at::kHalf && suh_cat.is_contiguous() && suh_cat.numel() == shards * k);
  TORCH_CHECK(svh_cat.dtype() == at::kHalf && svh_cat.numel() == n && svh_cat.is_contiguous());
  if (m == 0) return;
  cudaStream_t stream = at::cuda::getCurrentCUDAStream().stream();
  trellis_exl3_marlin::gemm_launch((const half*)xh.data_ptr(), b.data_ptr(), (half*)y.data_ptr(), (int)m, (int)n, (int)k,
                                  (int)cb, kb, x.get_device(), stream, -1, -1, shard_ends,
                                  (const half*)svh_cat.data_ptr(), y.dtype() == at::kBFloat16, x.data_ptr(),
                                  x.dtype() == at::kBFloat16, (const half*)suh_cat.data_ptr());
}

at::Tensor exl3_linear_marlin(const at::Tensor& x, const at::Tensor& b, const at::Tensor& suh, const at::Tensor& svh,
                              int64_t cb) {
  auto xh = at::empty(x.sizes(), x.options().dtype(at::kHalf));
  auto y = at::empty({x.size(0), b.size(1) * 64}, x.options());
  exl3_linear_marlin_out(x, b, suh, svh, cb, xh, y);
  return y;
}

